import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const sourcePath = path.join(root, 'dist', 'hud.inject.js');
const headerPath = path.join(root, 'asi_plugin', 'src', 'embedded_hud.h');
const source = fs.readFileSync(sourcePath);

const lines = [];
for (let offset = 0; offset < source.length; offset += 16) {
  const slice = source.subarray(offset, Math.min(source.length, offset + 16));
  const bytes = [...slice].map((value) => `0x${value.toString(16).padStart(2, '0')}`);
  lines.push(`  ${bytes.join(', ')},`);
}

const header = `#pragma once

/* Generated by scripts/embed-to-cpp.mjs. Do not edit by hand. */

static const unsigned char kEmbeddedHud[] = {
${lines.join('\n')}
};

static const unsigned int kEmbeddedHudSize = ${source.length};
`;

fs.mkdirSync(path.dirname(headerPath), { recursive: true });
fs.writeFileSync(headerPath, header);
console.log(`embedded ${source.length} bytes into ${headerPath}`);
